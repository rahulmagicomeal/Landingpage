/**
 * thankyou.js — renders public/thankyou.php.
 *
 * The visitor lands here after a successful form submit, so this page is
 * also the natural place to point a Google Ads destination-URL conversion.
 *
 * It is PHP rather than HTML for two reasons:
 *   - it sends its own `X-Robots-Tag: noindex` header. A thank-you page that
 *     gets indexed shows up in search results, which means people reach it
 *     without ever submitting the form — and every one of them is counted as
 *     a conversion.
 *   - it echoes the reference number from ?id=. That value is ONLY ever
 *     escaped and printed. It is never used to look a lead up: an endpoint
 *     that returned lead details for an id would let anyone walk the whole
 *     pipeline by guessing ids.
 */
const company = require('./data/company');
const content = require('./data/content');

const esc = (s) =>
  String(s == null ? '' : s)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');

module.exports = function renderThankYou(config, assetVersions) {
  const co = company;
  const s = content.form.success;
  const v = assetVersions.css ? `?v=${assetVersions.css}` : '';
  const telHref = `tel:${co.contact.phone}`;
  const waHref = `https://wa.me/${co.contact.whatsapp}?text=${encodeURIComponent(s.whatsappText)}`;
  const backHref = config.site.path;

  /* What actually happens next. Kept deliberately modest: these are the
   * steps Magicomeal already commits to on the form, not invented SLAs. */
  const steps = [
    {
      h: 'We read your requirement',
      p: `Your PAX count, location and cuisine preferences go straight to the catering team.`,
    },
    {
      h: 'We call you back',
      p: `Usually within one working day, during ${esc(co.contact.hours)}.`,
    },
    {
      h: 'You get a costed proposal',
      p: 'Menu options and per-head pricing for your site, with a tasting if you want one.',
    },
  ];

  return `<?php
/**
 * thankyou.php — GENERATED by src/thankyou.js. Do not edit this file.
 * Change src/thankyou.js or the data layer, then run: npm run build
 *
 * noindex is deliberate and important: an indexed thank-you page is reachable
 * from search without submitting the form, and every such visit is counted as
 * a conversion.
 */
header('X-Robots-Tag: noindex, nofollow', true);

/* Printed as a reference only. Never used to look up a lead — see the note
 * in src/thankyou.js. Trimmed to the shape our own ids actually take. */
$ref = isset($_GET['id']) ? substr(preg_replace('/[^A-Za-z0-9-]/', '', (string)$_GET['id']), 0, 40) : '';
?>
<!doctype html>
<html lang="en-IN">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex, nofollow">
<title>Thank you — ${esc(co.name)}</title>
<link rel="icon" href="assets/img/magicomeal-logo-badge.png">
<link rel="stylesheet" href="assets/css/styles.css${v}">
<style>
  /* This page is a single centred card, so it carries the few rules it
     needs rather than adding dead weight to the landing page stylesheet. */
  .ty{min-height:100vh;display:flex;align-items:center;justify-content:center;padding:32px 16px;background:var(--bg,#f6f8f6)}
  .ty__card{width:100%;max-width:640px;background:#fff;border-radius:16px;padding:40px 32px;box-shadow:0 12px 40px rgba(0,0,0,.08);text-align:center}
  @media (max-width:480px){
    .ty{padding:16px 12px}
    .ty__card{padding:28px 20px}
  }
  .ty__tick{width:72px;height:72px;margin:0 auto 24px;border-radius:50%;background:#e8f5e9;display:flex;align-items:center;justify-content:center}
  .ty__tick svg{width:36px;height:36px;stroke:#2e7d32;stroke-width:3;fill:none;stroke-linecap:round;stroke-linejoin:round}
  .ty__h1{font-size:clamp(22px,4vw,30px);line-height:1.25;margin:0 0 12px;color:#1b2a1c}
  .ty__lead{font-size:17px;line-height:1.6;color:#44584a;margin:0 0 32px}
  .ty__steps{list-style:none;margin:0 0 28px;padding:0;text-align:left;counter-reset:ty}
  .ty__steps li{position:relative;padding:0 0 20px 46px;counter-increment:ty}
  .ty__steps li::before{content:counter(ty);position:absolute;left:0;top:0;width:30px;height:30px;border-radius:50%;background:#2e7d32;color:#fff;font-weight:700;font-size:14px;display:flex;align-items:center;justify-content:center}
  .ty__steps b{display:block;color:#1b2a1c;font-size:16px;margin-bottom:3px}
  .ty__steps span{color:#55685a;font-size:15px;line-height:1.5}
  /* The phone CTA comes before the "what happens next" steps. Someone who
     has just converted is at their most willing to call, and on a phone the
     steps alone pushed the button a full screen below the fold. */
  .ty__cta{display:flex;gap:12px;flex-wrap:wrap;justify-content:center;margin:0 0 32px}
  .ty__cta a{flex:1 1 220px;min-height:52px;display:flex;align-items:center;justify-content:center;gap:9px;border-radius:10px;font-weight:600;font-size:16px;text-decoration:none;padding:14px 20px}
  .ty__call{background:#2e7d32;color:#fff}
  .ty__wa{background:#fff;color:#1b5e20;border:2px solid #2e7d32}
  .ty__cta a:hover{filter:brightness(.95)}
  .ty__meta{font-size:14px;color:#6b7d70;border-top:1px solid #e4ebe5;padding-top:20px;margin:0}
  .ty__meta a{color:#2e7d32}
  .ty__ref{display:block;margin-top:8px;font-size:13px;color:#90a094}
  @media (prefers-color-scheme:dark){
    .ty{background:#12170f}
    .ty__card{background:#1b2118;box-shadow:none}
    .ty__h1,.ty__steps b{color:#eaf3ea}
    .ty__lead,.ty__steps span{color:#b6c6b8}
    .ty__wa{background:transparent;color:#9ccf9f}
    .ty__meta{color:#9aab9c;border-top-color:#2a3327}
  }
</style>
</head>
<body>
<main class="ty">
  <div class="ty__card">
    <div class="ty__tick" aria-hidden="true">
      <svg viewBox="0 0 24 24"><path d="M20 6 9 17l-5-5"/></svg>
    </div>

    <h1 class="ty__h1">${esc(s.h3)}</h1>
    <p class="ty__lead">${esc(s.body)}</p>

    <div class="ty__cta">
      <a class="ty__call" href="${esc(telHref)}">Call ${esc(co.contact.phoneDisplay)}</a>
      <a class="ty__wa" href="${esc(waHref)}" target="_blank" rel="noopener">WhatsApp us</a>
    </div>

    <ol class="ty__steps">
${steps.map((x) => `      <li><b>${x.h}</b><span>${x.p}</span></li>`).join('\n')}
    </ol>

    <p class="ty__meta">
      Prefer email? <a href="mailto:${esc(co.contact.email)}">${esc(co.contact.email)}</a><br>
      <a href="${esc(backHref)}">Back to corporate catering</a>
      <?php if ($ref !== '') { ?>
        <span class="ty__ref">Reference: <?php echo htmlspecialchars($ref, ENT_QUOTES, 'UTF-8'); ?></span>
      <?php } ?>
    </p>
  </div>
</main>
</body>
</html>
`;
};
